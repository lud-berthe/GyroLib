static const char* find_text(std::string_view language,const char* key) {
    const Text wanted{language.data(),key,nullptr};
    const auto it=std::lower_bound(std::begin(texts),std::end(texts),wanted,
        [language](const Text& text,const Text& value) {
            const int order=std::string_view(text.language).compare(language);
            return order<0 || (order==0 && std::strcmp(text.key,value.key)<0);
        });
    return it!=std::end(texts) && language==it->language && std::strcmp(key,it->key)==0 ? it->value : nullptr;
}
const char* translate(std::string_view language,const char* key) {
    if(!key)return "?";
    if(const auto* value=find_text(language,key))return value;
    if(language!="en")if(const auto* value=find_text("en",key))return value;
    return "?";
}
